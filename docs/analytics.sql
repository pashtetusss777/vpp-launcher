-- Таблица принимает строки только от ключа anon; читать и менять их через API нельзя.

create table if not exists public.usage_events (
  id bigint generated by default as identity primary key,
  client_id uuid not null,
  event text not null check (event in ('launch', 'session_end')),
  launcher_version text,
  os text,
  os_version text,
  arch text,
  cpu_cores int,
  ram_gb int,
  ram_allocated_gb int,
  gpu text,
  game text,
  pack text,
  duration_s int,
  exit_code int,
  crashed boolean,
  at timestamptz not null default now()
);

alter table public.usage_events enable row level security;

drop policy if exists "anon inserts only" on public.usage_events;
create policy "anon inserts only"
  on public.usage_events
  for insert
  to anon
  with check (true);

